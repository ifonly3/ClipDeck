import AppKit
import Combine
import Foundation

/// Why a clipboard change was intentionally not recorded.
enum CaptureSkipReason: Sendable, Equatable {
    /// The source app marked the content as concealed, transient, or generated.
    case markedContent(String)
    /// The content came from an app the user chose to ignore.
    case ignoredApplication(String)
}

/// An immutable snapshot of the capture privacy policy, evaluated before any
/// clipboard data is read so skipped content never enters ClipDeck's memory.
struct CapturePrivacyRules: Sendable, Equatable {
    /// Markers defined by nspasteboard.org plus widely used legacy equivalents.
    /// Password managers and text expanders set these on purpose.
    static let markerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb"
    ]
    /// nspasteboard.org: the bundle identifier of the app that wrote the data.
    static let sourceType = "org.nspasteboard.source"

    var skipsMarkedContent = true
    var ignoredBundleIdentifiers: Set<String> = []
    /// The frontmost app when the change was noticed. It is only consulted
    /// when the writer did not declare `org.nspasteboard.source`.
    var frontmostBundleIdentifier: String?

    static let disabled = CapturePrivacyRules(skipsMarkedContent: false)

    func skipReason(types: [String], declaredSource: String?) -> CaptureSkipReason? {
        if skipsMarkedContent, let marker = types.first(where: Self.markerTypes.contains) {
            return .markedContent(marker)
        }
        let trimmedSource = declaredSource?.trimmingCharacters(in: .whitespacesAndNewlines)
        let source = trimmedSource?.isEmpty == false ? trimmedSource : frontmostBundleIdentifier
        if let source, ignoredBundleIdentifiers.contains(source) {
            return .ignoredApplication(source)
        }
        return nil
    }
}

/// User-facing privacy preferences persisted in UserDefaults. The values are
/// settings only; clipboard content is never written to disk.
@MainActor
final class CapturePrivacySettings: ObservableObject {
    static let skipsMarkedContentKey = "com.qiaoni.ClipDeck.skipsMarkedContent"
    static let ignoredApplicationsKey = "com.qiaoni.ClipDeck.ignoredApplications"
    /// Apple's password apps do not always mark copied secrets.
    static let defaultIgnoredBundleIdentifiers = ["com.apple.Passwords", "com.apple.keychainaccess"]

    @Published var skipsMarkedContent: Bool {
        didSet {
            guard skipsMarkedContent != oldValue else { return }
            defaults.set(skipsMarkedContent, forKey: Self.skipsMarkedContentKey)
        }
    }
    @Published private(set) var ignoredBundleIdentifiers: [String]

    private let defaults: UserDefaults

    init(defaults: UserDefaults = .standard) {
        self.defaults = defaults
        skipsMarkedContent = defaults.object(forKey: Self.skipsMarkedContentKey) as? Bool ?? true
        ignoredBundleIdentifiers = defaults.stringArray(forKey: Self.ignoredApplicationsKey)
            ?? Self.defaultIgnoredBundleIdentifiers
    }

    var rules: CapturePrivacyRules {
        CapturePrivacyRules(
            skipsMarkedContent: skipsMarkedContent,
            ignoredBundleIdentifiers: Set(ignoredBundleIdentifiers)
        )
    }

    var usesDefaultIgnoredApplications: Bool {
        ignoredBundleIdentifiers == Self.defaultIgnoredBundleIdentifiers
    }

    /// Returns false when the URL is not an application bundle with an identifier.
    @discardableResult
    func ignoreApplication(at url: URL) -> Bool {
        guard let identifier = Bundle(url: url)?.bundleIdentifier else { return false }
        ignore(bundleIdentifier: identifier)
        return true
    }

    func ignore(bundleIdentifier: String) {
        let identifier = bundleIdentifier.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !identifier.isEmpty,
              identifier != Bundle.main.bundleIdentifier,
              !ignoredBundleIdentifiers.contains(identifier) else { return }
        update(ignoredBundleIdentifiers + [identifier])
    }

    func stopIgnoring(bundleIdentifier: String) {
        update(ignoredBundleIdentifiers.filter { $0 != bundleIdentifier })
    }

    func restoreDefaultIgnoredApplications() {
        update(Self.defaultIgnoredBundleIdentifiers)
    }

    private func update(_ identifiers: [String]) {
        ignoredBundleIdentifiers = identifiers
        defaults.set(identifiers, forKey: Self.ignoredApplicationsKey)
    }
}

/// Resolves a bundle identifier to the installed app's name and icon for display.
struct IgnoredApplicationInfo: Identifiable {
    let bundleIdentifier: String
    let name: String
    let icon: NSImage?
    let isInstalled: Bool

    var id: String { bundleIdentifier }

    @MainActor
    init(bundleIdentifier: String, workspace: NSWorkspace = .shared) {
        self.bundleIdentifier = bundleIdentifier
        if let url = workspace.urlForApplication(withBundleIdentifier: bundleIdentifier) {
            let displayName = FileManager.default.displayName(atPath: url.path)
            name = displayName.hasSuffix(".app") ? String(displayName.dropLast(4)) : displayName
            icon = workspace.icon(forFile: url.path)
            isInstalled = true
        } else {
            name = bundleIdentifier
            icon = nil
            isInstalled = false
        }
    }
}
